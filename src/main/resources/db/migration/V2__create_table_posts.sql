CREATE TABLE tb_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    content TEXT NOT NULL,
    status VARCHAR(20) NOT NULL,
    author_name VARCHAR(100) NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_posts_slug UNIQUE (slug)
);

CREATE INDEX idx_posts_created_at_desc ON tb_posts(created_at DESC);
CREATE INDEX idx_posts_published_at_desc ON tb_posts(published_at DESC);
CREATE INDEX idx_posts_status ON tb_posts(status);
